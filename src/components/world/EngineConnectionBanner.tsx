import clsx from 'clsx'
import { worldApiBaseUrl } from '../../services/engineConfig'

export type EngineConnectionKind = 'probing' | 'live' | 'mock' | 'unavailable'

interface Props {
  kind: EngineConnectionKind
  detail?: string
  engineName?: string | null
}

export function EngineConnectionBanner({ kind, detail, engineName }: Props) {
  const styles: Record<EngineConnectionKind, string> = {
    probing: 'border-line bg-panel text-soft',
    live: 'border-ok/40 bg-ok/10 text-ok',
    mock: 'border-mock/40 bg-mock/10 text-mock',
    unavailable: 'border-danger/40 bg-danger/10 text-bright',
  }

  const title: Record<EngineConnectionKind, string> = {
    probing: 'Checking Waypoint GPU server…',
    live: 'Waypoint GPU connected — genuine interactive generation',
    mock: 'Protocol mock only — not genuine Waypoint generation',
    unavailable: 'Waypoint model server unavailable',
  }

  return (
    <div className={clsx('rounded-lg border px-4 py-3 text-sm', styles[kind])}>
      <p className="font-semibold">{title[kind]}</p>
      <p className="mt-1 text-xs leading-relaxed opacity-90">
        {kind === 'unavailable' && (
          <>
            Connection failed to{' '}
            <code className="text-signal">{worldApiBaseUrl()}</code>. This is not MOCK mode —
            the UI will not pretend frames are live. Start Codex Waypoint on :8000 and Retry, or
            restart the frontend with <code className="text-signal">npm run dev:mock</code> for an
            explicit protocol mock. Rescue Lab still works from{' '}
            <code className="text-signal">public/data/rescue/</code>.
          </>
        )}
        {kind === 'mock' && (
          <>
            Explicit MOCK stream (hello.mock / MockWaypointEngine). Not genuine GPU generation.
            For LIVE: stop mock, start Codex on :8000, run <code className="text-signal">npm run dev</code>.
          </>
        )}
        {kind === 'live' && (
          <>
            Engine {engineName ?? 'Waypoint'} is ready. Frames are generated by the local GPU model,
            not prerecorded video.
          </>
        )}
        {kind === 'probing' && <>Contacting {worldApiBaseUrl()}…</>}
        {detail ? ` ${detail}` : null}
      </p>
    </div>
  )
}
